# 동작별 이동 속도 (화면 기준 px/프레임, actions와 같은 순서). 0이면 제자리
speeds = [
    6,   # 1. 걷기 시작 / 가속
    20,  # 2. 달리기
    0,   # 3. 브레이크 / 회전 동작
    0,   # 4. 스핀
    25,  # 5. 볼 구르기
    30,  # 6. 빠른 달리기
    40,  # 7. 슈퍼 필아웃
    0,   # 8. 밀기 / 기타 자세
    10,  # 9. 걷기
    0,   # 10. 놀람 / 피격
]


def handle_events():
    global running
    events = get_events()
    for event in events:
        if event.type == SDL_QUIT:
            running = False
        elif event.type == SDL_KEYDOWN and event.key == SDLK_ESCAPE:
            running = False


open_canvas(CANVAS_WIDTH, CANVAS_HEIGHT)

sonic = load_image('sonic-sprite.png')

running = True
action = 0  # 지금 재생 중인 동작 (0부터)
frame = 0  # 동작 안의 프레임 번호
repeat = 0  # 지금 동작을 끝까지 재생한 횟수
pause = 0  # 남은 쉬는 프레임 수 (쉬는 동안에도 루프를 돌아 이벤트를 처리)
x = CENTER_X  # 캐릭터의 가로 위치
while running:
    clear_canvas()
    left, bottom, w, h = actions[action][frame]
    sonic.clip_draw(left, bottom, w, h, x, GROUND_Y + h * SCALE // 2, w * SCALE, h * SCALE)
    update_canvas()
    handle_events()
    if pause > 0:
        pause -= 1
        if pause == 0:
            action = (action + 1) % len(actions)  # 다음 동작, 마지막 다음은 처음으로
            frame = 0
            repeat = 0
            x = CENTER_X  # 새 동작은 중앙에서 시작
    else:
        x += speeds[action]
        frame += 1
        if frame == len(actions[action]):
            repeat += 1
            if repeat < REPEAT_COUNT:
                frame = 0
            else:
                frame -= 1  # 5회 끝: 마지막 프레임이 화면에 남은 채로 쉬기
                pause = round(PAUSE_TIME / FRAME_TIME)
    delay(FRAME_TIME)

close_canvas()
