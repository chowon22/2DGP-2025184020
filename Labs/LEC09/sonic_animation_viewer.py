action = 0  # 재생할 동작 번호 (0부터)


def handle_events():
    global running
    events = get_events()
    for event in events:
        if event.type == SDL_QUIT:
            running = False
        elif event.type == SDL_KEYDOWN and event.key == SDLK_ESCAPE:
            running = False


open_canvas(800, 600)

sonic = load_image('sonic-sprite.png')

running = True
frame = 0
repeat = 0
while running:
    clear_canvas()
    left, bottom, w, h = actions[action][frame]
    sonic.clip_draw(left, bottom, w, h, CENTER_X, GROUND_Y + h * SCALE // 2, w * SCALE, h * SCALE)
    update_canvas()
    handle_events()
    if repeat < REPEAT_COUNT:
        frame += 1
        if frame == len(actions[action]):
            repeat += 1
            if repeat < REPEAT_COUNT:
                frame = 0
            else:
                delay(PAUSE_TIME)  # 마지막 프레임이 화면에 남은 채로 쉬기
                action = (action + 1) % len(actions)  # 5회 끝: 다음 동작, 마지막 다음은 처음으로
                frame = 0
                repeat = 0
    delay(FRAME_TIME)

close_canvas()
